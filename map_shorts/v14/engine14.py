def sig(x):
    k = 10.0
    lo, hi = 1 / (1 + math.exp(k * 0.5)), 1 / (1 + math.exp(-k * 0.5))
    return (1 / (1 + math.exp(-k * (x - 0.5))) - lo) / (hi - lo)


CX0, CX1, CY0, CY1 = 330, 1640, 820, 190


def cpt(x):
    return CX0 + x * (CX1 - CX0), CY0 - sig(x) * (CY0 - CY1)


def slope_angle(x):
    x1, y1 = cpt(max(0, x - 0.01))
    x2, y2 = cpt(min(1, x + 0.01))
    return math.degrees(math.atan2(-(y2 - y1), x2 - x1))


def rotated_label(img, s, xy, angle, size=46, fill=GREEN):
    f = font(size, "Bold")
    w_ = int(f.getlength(s)) + 20
    lay = Image.new("RGBA", (w_, size * 2), (0, 0, 0, 0))
    ImageDraw.Draw(lay).text((w_ / 2, size), s, font=f, fill=fill, anchor="mm")
    lay = lay.rotate(angle, expand=True, resample=Image.BICUBIC)
    img.alpha_composite(lay, (int(xy[0] - lay.width / 2), int(xy[1] - lay.height / 2)))


