def gen_len(name):
    return 5.0 if name.startswith("gen:ws_") else 4.0
_pool_i = [0]


def pick_broll(line, prev):
    name = TOPIC.get(line)
    if name and name != prev:
        return name
    for _ in range(len(POOL)):
        name = POOL[_pool_i[0] % len(POOL)]
        _pool_i[0] += 1
        if name != prev:
            return name
    return POOL[0]


def build_shots():
    shots = []
    n = len(SCRIPT)
    for i, (text, sc) in enumerate(SCRIPT):
        scs = sc if isinstance(sc, list) else [sc]
        t0 = 0.0 if i == 0 else starts[i] - 0.15
        t1 = (starts[i + 1] - 0.15) if i + 1 < n else LAST_END
        fixed = sum(s.get("d", 0) for s in scs)
        ws = [0 if "d" in s else s.get("w", 1.0) for s in scs]
        tot = sum(ws) or 1
        durs = [s["d"] if "d" in s else (t1 - t0 - fixed) * w / tot for s, w in zip(scs, ws)]
        for k, s in enumerate(scs):  # generated clips are only 4 s long
            if s["t"] == "clip" and s["src"].startswith("gen:") and durs[k] > gen_len(s["src"]):
                extra = durs[k] - gen_len(s["src"])
                durs[k] = gen_len(s["src"])
                others = [j for j, o in enumerate(scs) if j != k and not (o["t"] == "clip" and o["src"].startswith("gen:"))]
                if others:
                    durs[others[0]] += extra
                else:
                    durs[k] += extra
        t = t0
        line_shots = []
        for k, (s, d) in enumerate(zip(scs, durs)):
            line_shots.append(dict(t0=t, t1=t + d, sc=s, line=i, k=k))
            t += d
        out, kk, prev = [], 100, None
        for sh in line_shots:
            d = sh["t1"] - sh["t0"]
            if sh["sc"]["t"] not in ("clip", "title", "quote") and d > 5.8:
                g = min(max(3.4, d * 0.56), d - 2.2)
                nm = pick_broll(i, prev)
                out.append(dict(t0=sh["t0"], t1=sh["t0"] + g, sc=sh["sc"], line=i, k=sh["k"]))
                out.append(dict(t0=sh["t0"] + g, t1=sh["t1"], sc=dict(t="clip", src=nm), line=i, k=kk))
                kk += 1
                prev = nm
            else:
                out.append(sh)
                prev = sh["sc"].get("src") if sh["sc"]["t"] == "clip" else prev
        shots += out
    shots.append(dict(t0=LAST_END, t1=TOTAL, sc=dict(t="endcard"), line=n, k=0))
    return shots


