def shot_at(t):
    lo, hi = 0, len(SHOTS) - 1
    while lo < hi:
        mid = (lo + hi) // 2
        if SHOTS[mid]["t1"] <= t:
            lo = mid + 1
        else:
            hi = mid
    return SHOTS[lo]


