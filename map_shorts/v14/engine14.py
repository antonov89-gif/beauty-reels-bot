def draw_hand(d, cx, cy, s, fingers=7, col=(214, 170, 140)):
    d.ellipse((cx - 150 * s, cy - 40 * s, cx + 150 * s, cy + 190 * s), fill=col)
    for j in range(fingers):
        a = -math.pi * (0.1 + 0.8 * j / (fingers - 1))
        L = (190 + 40 * math.sin(j * 1.9)) * s
        bx, by = cx + 110 * s * math.cos(a), cy + 20 * s + 80 * s * math.sin(a)
        ex, ey = bx + L * math.cos(a), by + L * math.sin(a)
        d.line([(bx, by), (ex, ey)], fill=col, width=int(44 * s))
        d.ellipse((ex - 22 * s, ey - 22 * s, ex + 22 * s, ey + 22 * s), fill=col)


def fit_still(name, box, zoom=1.0):
    im = still(name)
    w_, h_ = box[2] - box[0], box[3] - box[1]
    s = max(w_ / im.width, h_ / im.height) * zoom
    im = im.resize((int(im.width * s), int(im.height * s)), Image.BILINEAR)
    x0, y0 = (im.width - w_) // 2, (im.height - h_) // 2
    return im.crop((x0, y0, x0 + w_, y0 + h_)).convert("RGBA")


