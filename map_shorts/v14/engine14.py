def frame(fi):
    t = fi / FPS
    s = shot_at(t)
    sc = s["sc"]
    p = (t - s["t0"]) / max(0.01, s["t1"] - s["t0"])
    lt = t - s["t0"]
    kind = sc["t"]
    if kind == "clip":
        img = clip_frame(s, t)
        if sc["src"].startswith("gen:"):
            tag(img, "GENERATED BY AI", W // 2, H - 150)
        if sc.get("tag") == "script":
            tag_left(img, "SCRIPT WRITTEN WITH AI", 70, H - 150)
    else:
        img = SCENES[kind](sc, p, lt, s) if kind == "curve" else SCENES[kind](sc, p, lt)
        if kind not in ("aipair", "chat", "endcard"):
            z = 1.0 + 0.022 * p  # slow push-in so graphics are never static
            cw, ch = int(W / z), int(H / z)
            x0, y0 = (W - cw) // 2, (H - ch) // 2
            img = img.crop((x0, y0, x0 + cw, y0 + ch)).resize((W, H), Image.BILINEAR)
        if kind == "chat":
            tag(img, "GENERATED BY AI", W // 2, H - 150)
    if kind != "endcard":
        subtitles(img, t)
    return img.convert("RGB")


