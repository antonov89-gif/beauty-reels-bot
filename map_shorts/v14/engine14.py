def clip_dir(s, suffix=""):
    return f"frames/{s['line']:02d}_{s['k']}{suffix}"


def bars(src):
    out = subprocess.run(["ffmpeg", "-loglevel", "error", "-ss", "1.5", "-i", src, "-frames:v", "1", "-f", "rawvideo",
                          "-pix_fmt", "gray", "-"], capture_output=True).stdout
    probe = subprocess.run(["ffprobe", "-v", "error", "-select_streams", "v:0", "-show_entries", "stream=width,height",
                            "-of", "csv=p=0", src], capture_output=True, text=True).stdout.strip().split(",")
    w, h = int(probe[0]), int(probe[1])
    a = np.frombuffer(out, np.uint8)[: w * h].reshape(h, w).astype(np.float32)
    rows = np.where(a.mean(1) > 12)[0]
    return (int(rows[0]), int(rows[-1]) + 1, w, h) if len(rows) else (0, h, w, h)


_used = {}


def extract(name, out, dur, size=(1920, 1080), grade=True):
    """extract `dur` seconds of clip `name` (stock or gen:) to jpg frames of `size` into dir `out`."""
    os.makedirs(out, exist_ok=True)
    sw, sh = size
    eq = ",eq=contrast=1.04:saturation=1.06" if grade else ""
    if name.startswith("gen:"):
        src = f"gen/{name[4:]}.mp4"
        top, bot, w, h = bars(src)
        ph = bot - top
        cw = min(w, int(ph * 16 / 9))
        ch = int(cw * 9 / 16)
        x0 = (w - cw) // 2
        y0 = top + (ph - ch) // 2
        vf = f"crop={cw}:{ch}:{x0}:{y0},scale={sw}:{sh}:flags=lanczos,fps=30{eq}"
        subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", src, "-vf", vf, "-frames:v",
                        str(int(min(dur, gen_len(name)) * FPS)), "-start_number", "1", "-q:v", "3", f"{out}/%05d.jpg"],
                       check=True)
        return
    src = f"media/{name}.mp4"
    clen = float(subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", src],
                                capture_output=True, text=True).stdout.strip() or 0)
    off = _used.get(name, 0.4)
    if off + dur > clen:
        off = max(0, clen - dur - 0.05)
    _used[name] = off + dur
    speed = 1.0 if clen - off >= dur else max(0.3, (clen - off) / dur * 0.98)
    vf = (f"setpts={1 / speed:.4f}*PTS,scale={sw}:{sh}:force_original_aspect_ratio=increase,crop={sw}:{sh},fps=30{eq}")
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-ss", f"{off:.2f}", "-i", src, "-t", f"{dur * speed:.2f}",
                    "-vf", vf, "-frames:v", str(int(dur * FPS) + 2), "-start_number", "1", "-q:v", "3",
                    f"{out}/%05d.jpg"], check=True)


def prep():
    os.makedirs("frames", exist_ok=True)
    os.makedirs("stills", exist_ok=True)
    for s in SHOTS:
        sc = s["sc"]
        dur = s["t1"] - s["t0"] + 0.25
        if sc["t"] == "clip":
            extract(sc["src"], clip_dir(s), dur)
            print("clip", clip_dir(s), flush=True)
        elif sc["t"] == "curve" and sc.get("pip"):
            names = sc["pip"]
            for j, nm in enumerate(names):
                extract(nm, clip_dir(s, f"_pip{j}"), dur / len(names) + 0.3, size=(640, 360), grade=False)
            print("pip", clip_dir(s), flush=True)
        for nm in (sc.get("names") or []) + ([sc["still"]] if sc.get("still") else []):
            path = f"stills/{nm}.jpg"
            if os.path.exists(path):
                continue
            src = f"gen/{nm}.mp4"
            top, bot, w, h = bars(src)
            ph = bot - top
            cw = min(w, int(ph * 16 / 9))
            ch = int(cw * 9 / 16)
            vf = f"crop={cw}:{ch}:{(w - cw) // 2}:{top + (ph - ch) // 2},scale=1280:720:flags=lanczos"
            subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-ss", "2.0", "-i", src, "-vf", vf, "-frames:v", "1",
                            "-q:v", "2", path], check=True)


_NCACHE = {}


def n_frames(d):
    if d not in _NCACHE:
        _NCACHE[d] = len([f for f in os.listdir(d) if f.endswith(".jpg")])
    return _NCACHE[d]


def frame_img(d, t0, t):
    n = n_frames(d)
    i = max(1, min(n, int((t - t0) * FPS) + 1))
    return Image.open(f"{d}/{i:05d}.jpg").convert("RGB")


def clip_frame(s, t):
    img = frame_img(clip_dir(s), s["t0"], t)
    p = (t - s["t0"]) / max(0.01, s["t1"] - s["t0"])
    z = 1.0 + 0.055 * p if s["k"] % 2 == 0 else 1.055 - 0.055 * p
    cw, ch = int(W / z), int(H / z)
    x0, y0 = (W - cw) // 2, (H - ch) // 2
    return img.crop((x0, y0, x0 + cw, y0 + ch)).resize((W, H), Image.BILINEAR).convert("RGBA")


