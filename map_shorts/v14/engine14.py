def ease(x):
    x = min(1.0, max(0.0, x))
    return x * x * (3 - 2 * x)


def out_back(x, s=1.70158):
    x = min(1.0, max(0.0, x))
    return 1 + (s + 1) * (x - 1) ** 3 + s * (x - 1) ** 2


def out_cubic(x):
    x = min(1.0, max(0.0, x))
    return 1 - (1 - x) ** 3


