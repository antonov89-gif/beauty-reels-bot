_BG = None


def background():
    global _BG
    if _BG is None:
        yy, xx = np.mgrid[0:H, 0:W].astype(np.float32)
        r = np.sqrt((xx - W * 0.5) ** 2 + (yy - H * 0.45) ** 2) / (W * 0.8)
        k = np.clip(r, 0, 1)[..., None]
        a = np.array(BG, np.float32) * (1 - 0.06 * k)
        _BG = Image.fromarray(a.astype(np.uint8)).convert("RGBA")
    return _BG.copy()


def text(d, xy, s, size, weight="Bold", fill=INK, anchor="mm", stroke=0, stroke_fill=(0, 0, 0)):
    d.text(xy, s, font=font(size, weight), fill=fill, anchor=anchor, stroke_width=stroke, stroke_fill=stroke_fill)


def wrap(s, f, maxw):
    words, lines, cur = s.split(), [], ""
    for w_ in words:
        trial = (cur + " " + w_).strip()
        if f.getlength(trial) <= maxw or not cur:
            cur = trial
        else:
            lines.append(cur)
            cur = w_
    if cur:
        lines.append(cur)
    return lines


def rrect(d, box, r, fill=None, outline=None, width=2):
    d.rounded_rectangle(box, radius=r, fill=fill, outline=outline, width=width)


def layer():
    return Image.new("RGBA", (W, H), (0, 0, 0, 0))


def fade(lay, a):
    if a >= 0.999:
        return lay
    lay = lay.copy()
    lay.putalpha(lay.getchannel("A").point(lambda v: int(v * max(0.0, a))))
    return lay


def paste_scaled(base, lay, cx, cy, s, alpha=1.0):
    if s <= 0.01 or alpha <= 0:
        return
    lay = fade(lay, alpha)
    if abs(s - 1) > 0.003:
        lay = lay.resize((max(1, int(W * s)), max(1, int(H * s))), Image.BILINEAR)
        full = layer()
        full.paste(lay, (int(cx - cx * s), int(cy - cy * s)))
        lay = full
    base.alpha_composite(lay)


